using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;

namespace PasheCPE.GeneradorRecursos;

/// <summary>
/// Genera las clases de constantes de catálogo (<c>CodigosSunat.g.cs</c>). El nombre de cada constante se toma de
/// <c>nombres-constantes.json</c>; los códigos nuevos reciben un nombre derivado de su descripción, que se agrega al
/// archivo y desde entonces queda fijo aunque SUNAT cambie el texto.
/// </summary>
internal static partial class GeneradorConstantes
{
    private const int _maximoPalabras = 6;

    public static (string Codigo, IReadOnlyList<ClaseConstantes> Nombres, int Nuevas, int Retiradas) Generar(
        IReadOnlyList<Catalogo> catalogos,
        IReadOnlyList<ClaseConstantes> clases,
        UnidadesCuradas unidades,
        string archivoExcel)
    {
        var porNumero = catalogos.ToDictionary(c => c.Numero, StringComparer.Ordinal);
        var nombres = new List<ClaseConstantes>();
        var nuevas = 0;
        var retiradas = 0;

        var codigo = new StringBuilder();
        codigo.Append("// <auto-generated>\n")
            .Append("// Generado por tools/GeneradorRecursos desde ").Append(archivoExcel).Append(".\n")
            .Append("// No editar: ejecutar `dotnet run --project tools/GeneradorRecursos`.\n")
            .Append("// </auto-generated>\n\n")
            .Append("namespace PasheCPE;\n");

        foreach (var clase in clases)
        {
            if (!porNumero.TryGetValue(clase.Catalogo, out var catalogo))
            {
                throw new InvalidDataException($"La clase {clase.Clase} apunta al catálogo {clase.Catalogo}, que no existe en el Excel.");
            }

            var existentes = clase.Constantes.ToDictionary(c => c.Codigo, c => c.Nombre, StringComparer.Ordinal);
            var usados = new HashSet<string>(StringComparer.Ordinal) { clase.Clase, "NumeroCatalogo" };
            var constantes = new List<NombreConstante>();
            foreach (var item in catalogo.Items.DistinctBy(i => i.Codigo))
            {
                if (!existentes.TryGetValue(item.Codigo, out var nombre))
                {
                    nombre = Derivar(item.Descripcion, item.Codigo);
                    nuevas++;
                }

                if (!usados.Add(nombre))
                {
                    nombre = $"{nombre}_{Identificador().Replace(item.Codigo, string.Empty)}";
                    usados.Add(nombre);
                }

                constantes.Add(new NombreConstante(item.Codigo, nombre));
            }

            retiradas += existentes.Keys.Count(c => !constantes.Exists(k => k.Codigo == c));
            nombres.Add(clase with { Constantes = constantes });

            codigo.Append('\n')
                .Append("/// <summary>Catálogo N.° ").Append(catalogo.Numero).Append(" de SUNAT: ").Append(Xml(catalogo.Nombre)).Append(".</summary>\n")
                .Append("public static class ").Append(clase.Clase).Append('\n')
                .Append("{\n")
                .Append("    /// <summary>Número del catálogo SUNAT.</summary>\n")
                .Append("    public const string NumeroCatalogo = \"").Append(catalogo.Numero).Append("\";\n");

            foreach (var constante in constantes)
            {
                var item = catalogo.Items.First(i => i.Codigo == constante.Codigo);
                codigo.Append('\n')
                    .Append("    /// <summary><c>").Append(Xml(item.Codigo)).Append("</c>: ").Append(Xml(item.Descripcion)).Append(Vigencia(item)).Append("</summary>\n")
                    .Append("    public const string ").Append(constante.Nombre).Append(" = \"").Append(item.Codigo).Append("\";\n");
            }

            codigo.Append("}\n");
        }

        AgregarSinListado(codigo, porNumero, unidades);
        return (codigo.ToString(), nombres, nuevas, retiradas);
    }

    /// <summary>Clase de un catálogo que se valida por formato: cada código curado debe cumplir ese formato.</summary>
    private static void AgregarSinListado(StringBuilder codigo, Dictionary<string, Catalogo> porNumero, UnidadesCuradas curadas)
    {
        if (!porNumero.TryGetValue(curadas.Catalogo, out var catalogo) || catalogo.Formato is null)
        {
            throw new InvalidDataException($"La clase {curadas.Clase} requiere que el catálogo {curadas.Catalogo} exista y se valide por formato.");
        }

        var formato = new Regex(catalogo.Formato, RegexOptions.CultureInvariant, TimeSpan.FromSeconds(1));
        var invalidos = curadas.Unidades.Where(u => !formato.IsMatch(u.Codigo) || !Identificador().Replace(u.Nombre, string.Empty).Equals(u.Nombre, StringComparison.Ordinal)).Select(u => u.Codigo).ToList();
        var repetidos = curadas.Unidades.GroupBy(u => u.Codigo).Concat(curadas.Unidades.GroupBy(u => u.Nombre)).Where(g => g.Count() > 1).Select(g => g.Key).ToList();
        if (invalidos.Count > 0 || repetidos.Count > 0)
        {
            throw new InvalidDataException($"Unidades curadas no válidas en {curadas.Clase}: {string.Join(", ", invalidos.Concat(repetidos))}.");
        }

        codigo.Append('\n')
            .Append("/// <summary>\n")
            .Append("/// Catálogo N.° ").Append(catalogo.Numero).Append(" de SUNAT: ").Append(Xml(catalogo.Nombre)).Append(". ").Append(Xml(curadas.Fuente)).Append('\n')
            .Append("/// </summary>\n")
            .Append("public static class ").Append(curadas.Clase).Append('\n')
            .Append("{\n")
            .Append("    /// <summary>Número del catálogo SUNAT.</summary>\n")
            .Append("    public const string NumeroCatalogo = \"").Append(catalogo.Numero).Append("\";\n");
        foreach (var unidad in curadas.Unidades)
        {
            codigo.Append('\n')
                .Append("    /// <summary><c>").Append(Xml(unidad.Codigo)).Append("</c>: ").Append(Xml(unidad.Descripcion)).Append("</summary>\n")
                .Append("    public const string ").Append(unidad.Nombre).Append(" = \"").Append(unidad.Codigo).Append("\";\n");
        }

        codigo.Append("}\n");
    }

    /// <summary>Nombre PascalCase a partir de la descripción (hasta seis palabras, sin tildes).</summary>
    public static string Derivar(string descripcion, string codigo)
    {
        var palabras = Palabras().Matches(Texto.SinTildes(descripcion).Replace('ñ', 'n').Replace('Ñ', 'N'))
            .Select(m => m.Value)
            .Take(_maximoPalabras)
            .Select(p => char.ToUpperInvariant(p[0]) + p[1..].ToLowerInvariant());
        var nombre = string.Concat(palabras);
        if (nombre.Length == 0)
        {
            nombre = "Codigo" + Identificador().Replace(codigo, string.Empty);
        }

        return char.IsDigit(nombre[0]) ? "C" + nombre : nombre;
    }

    private static string Vigencia(ItemCatalogo item) => (item.Desde, item.Hasta) switch
    {
        ({ } desde, { } hasta) => string.Create(CultureInfo.InvariantCulture, $" Vigente del {desde:dd/MM/yyyy} al {hasta:dd/MM/yyyy}."),
        ({ } desde, null) => string.Create(CultureInfo.InvariantCulture, $" Vigente desde el {desde:dd/MM/yyyy}."),
        (null, { } hasta) => string.Create(CultureInfo.InvariantCulture, $" Vigente hasta el {hasta:dd/MM/yyyy}."),
        _ => string.Empty,
    };

    private static string Xml(string texto) =>
        texto.Replace("&", "&amp;", StringComparison.Ordinal)
            .Replace("<", "&lt;", StringComparison.Ordinal)
            .Replace(">", "&gt;", StringComparison.Ordinal);

    [GeneratedRegex(@"[A-Za-z0-9]+")]
    private static partial Regex Palabras();

    [GeneratedRegex(@"[^A-Za-z0-9]")]
    private static partial Regex Identificador();
}
